-- V003：定位表（人员定位文件接入）。表结构见 docs/04 第四节，写入规则见 docs/02 第四节。
-- 每份数据记着依据哪份文件的"数据上传时间"（SRC_DATA_TIME 等），只接受时间更新的数据。

CREATE TABLE POS_INGEST_FILE (
  ID           NUMBER GENERATED ALWAYS AS IDENTITY,
  FILE_NAME    VARCHAR2(200 CHAR) NOT NULL,
  FILE_TYPE    VARCHAR2(10 CHAR),
  MINE_CODE    VARCHAR2(12 CHAR),
  HEADER_TIME  TIMESTAMP(0),
  SHA256       CHAR(64 CHAR),
  SIZE_BYTES   NUMBER,
  STATUS       VARCHAR2(12 CHAR) NOT NULL,
  RECORD_COUNT NUMBER,
  ERROR_COUNT  NUMBER,
  ERROR_MSG    VARCHAR2(500 CHAR),
  RECEIVED_AT  TIMESTAMP(0),
  PROCESSED_AT TIMESTAMP(0) DEFAULT LOCALTIMESTAMP(0) NOT NULL,
  BACKUP_PATH  VARCHAR2(500 CHAR),
  CONSTRAINT PK_POS_INGEST_FILE PRIMARY KEY (ID),
  CONSTRAINT CK_POS_INGEST_FILE_STATUS
    CHECK (STATUS IN ('DONE', 'PARTIAL', 'FAILED', 'STALE', 'DUPLICATE', 'UNKNOWN'))
);

COMMENT ON TABLE  POS_INGEST_FILE              IS '每个定位文件的处理记录';
COMMENT ON COLUMN POS_INGEST_FILE.FILE_NAME    IS '文件名（不含目录）';
COMMENT ON COLUMN POS_INGEST_FILE.FILE_TYPE    IS '文件类型，如 RYSS；文件名不合法时为空';
COMMENT ON COLUMN POS_INGEST_FILE.MINE_CODE    IS '煤矿编码（来自文件名）';
COMMENT ON COLUMN POS_INGEST_FILE.HEADER_TIME  IS '文件头里的数据上传时间，判断新旧的依据；没解析到时为空';
COMMENT ON COLUMN POS_INGEST_FILE.SHA256       IS '内容摘要，用来去重；没读取内容（如符号链接）时为空';
COMMENT ON COLUMN POS_INGEST_FILE.SIZE_BYTES   IS '文件大小（字节）';
COMMENT ON COLUMN POS_INGEST_FILE.STATUS       IS 'DONE 成功 / PARTIAL 部分记录失败 / FAILED 失败 / STALE 过期未生效 / DUPLICATE 重复 / UNKNOWN 未识别类型';
COMMENT ON COLUMN POS_INGEST_FILE.RECORD_COUNT IS '成功入库的记录数';
COMMENT ON COLUMN POS_INGEST_FILE.ERROR_COUNT  IS '出错的记录数（不含警告）';
COMMENT ON COLUMN POS_INGEST_FILE.ERROR_MSG    IS '失败原因或部分成功的说明';
COMMENT ON COLUMN POS_INGEST_FILE.RECEIVED_AT  IS '文件在收件箱里的最后修改时间';
COMMENT ON COLUMN POS_INGEST_FILE.PROCESSED_AT IS '处理时间';
COMMENT ON COLUMN POS_INGEST_FILE.BACKUP_PATH  IS '备份或失败目录里的位置（相对于对应目录）';

-- 查重复：同名同摘要；不设唯一，重复的文件也要记一行 DUPLICATE
CREATE INDEX IX_POS_FILE_NAME_SHA ON POS_INGEST_FILE (FILE_NAME, SHA256);
-- 按类型找最新一份生效的文件（V_POS_IN_WELL、状态接口）：带上状态列，只读索引就能取到最大时间，不用回表
CREATE INDEX IX_POS_FILE_TYPE_TIME ON POS_INGEST_FILE (FILE_TYPE, STATUS, HEADER_TIME);

CREATE TABLE POS_INGEST_ERROR (
  ID       NUMBER GENERATED ALWAYS AS IDENTITY,
  FILE_ID  NUMBER NOT NULL,
  KIND     VARCHAR2(10 CHAR) NOT NULL,
  LINE_NO  NUMBER NOT NULL,
  RAW_TEXT VARCHAR2(1000 CHAR),
  REASON   VARCHAR2(200 CHAR) NOT NULL,
  CONSTRAINT PK_POS_INGEST_ERROR PRIMARY KEY (ID),
  CONSTRAINT FK_POS_INGEST_ERROR_FILE FOREIGN KEY (FILE_ID) REFERENCES POS_INGEST_FILE (ID),
  CONSTRAINT CK_POS_INGEST_ERROR_KIND CHECK (KIND IN ('ERROR', 'WARN'))
);

COMMENT ON TABLE  POS_INGEST_ERROR          IS '定位文件里有问题的记录（仅供运维排查，页面不展示）';
COMMENT ON COLUMN POS_INGEST_ERROR.KIND     IS 'ERROR 记录被跳过 / WARN 记录已入库但需要人工核对（如同一文件里卡编码重复）';
COMMENT ON COLUMN POS_INGEST_ERROR.LINE_NO  IS '第几条记录（文件头之后从 1 数起）';
COMMENT ON COLUMN POS_INGEST_ERROR.RAW_TEXT IS '记录原文，超长截断；含姓名，页面不展示';
COMMENT ON COLUMN POS_INGEST_ERROR.REASON   IS '原因';

CREATE INDEX IX_POS_ERROR_FILE ON POS_INGEST_ERROR (FILE_ID);

