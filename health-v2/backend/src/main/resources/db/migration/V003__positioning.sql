-- 全系统统一的"井下人数"口径：最新一份生效的 RYSS 里出入井标志为 1 的人
CREATE OR REPLACE VIEW V_POS_IN_WELL AS
SELECT s.*
  FROM POS_PERSON_STATE s
 WHERE s.IN_OUT_FLAG = 1
   AND s.SRC_DATA_TIME = (SELECT MAX(HEADER_TIME) FROM POS_INGEST_FILE
                           WHERE FILE_TYPE = 'RYSS' AND STATUS IN ('DONE', 'PARTIAL'));

CREATE TABLE POS_PRESENCE_DAILY (
  STAT_DATE      DATE NOT NULL,
  CARD_CODE      VARCHAR2(17 CHAR) NOT NULL,
  FIRST_IN_TIME  TIMESTAMP(0),
  LAST_OUT_TIME  TIMESTAMP(0),
  LAST_SEEN_TIME TIMESTAMP(0) NOT NULL,
  CONSTRAINT PK_POS_PRESENCE_DAILY PRIMARY KEY (STAT_DATE, CARD_CODE)
);

COMMENT ON TABLE  POS_PRESENCE_DAILY                IS '每人每天的入井/出井记录（按 RYSS 快照日期，跨零点的夜班两天各一行）';
COMMENT ON COLUMN POS_PRESENCE_DAILY.STAT_DATE      IS 'RYSS 文件头时间的日期';
COMMENT ON COLUMN POS_PRESENCE_DAILY.FIRST_IN_TIME  IS '最早入井时刻（可能是前一天）';
COMMENT ON COLUMN POS_PRESENCE_DAILY.LAST_OUT_TIME  IS '最晚出井时刻';
COMMENT ON COLUMN POS_PRESENCE_DAILY.LAST_SEEN_TIME IS '当天最后一次以"已入井"出现在快照里的快照时间';

CREATE INDEX IX_POS_PRESENCE_CARD ON POS_PRESENCE_DAILY (CARD_CODE, STAT_DATE);

