CREATE TABLE ALERT_EVENT (
  ID               NUMBER GENERATED ALWAYS AS IDENTITY,
  CARD_CODE        VARCHAR2(17 CHAR),
  SRC              VARCHAR2(10 CHAR) NOT NULL,
  CODE             VARCHAR2(20 CHAR) NOT NULL,
  CATEGORY         VARCHAR2(20 CHAR) NOT NULL,
  SEVERITY         NUMBER(1) NOT NULL,
  VAL_TEXT         VARCHAR2(50 CHAR),
  RULE_GROUP       VARCHAR2(20 CHAR),
  OCCURRED_AT      TIMESTAMP(0) NOT NULL,
  LAST_OCCURRED_AT TIMESTAMP(0) NOT NULL,
  OCCUR_COUNT      NUMBER(6) DEFAULT 1 NOT NULL,
  DEVICE_IMEI      VARCHAR2(15 CHAR),
  CONSTRAINT PK_ALERT_EVENT PRIMARY KEY (ID),
  CONSTRAINT CK_ALERT_EVENT_SRC CHECK (SRC IN ('THRESHOLD', 'DEVICE')),
  CONSTRAINT CK_ALERT_EVENT_CATEGORY
    CHECK (CATEGORY IN ('SOS', 'FALL', 'HEART_RATE', 'BLOOD_PRESSURE', 'SPO2', 'TEMPERATURE', 'OTHER')),
  CONSTRAINT CK_ALERT_EVENT_SEVERITY CHECK (SEVERITY IN (1, 2, 3)),
  -- 没有卡编码时必须有设备号，否则无法区分是谁
  CONSTRAINT CK_ALERT_EVENT_WHO CHECK (CARD_CODE IS NOT NULL OR DEVICE_IMEI IS NOT NULL),
  -- 一条事件不跨天（docs/03 第四节）
  CONSTRAINT CK_ALERT_EVENT_SAME_DAY
    CHECK (TRUNC(LAST_OCCURRED_AT) = TRUNC(OCCURRED_AT) AND LAST_OCCURRED_AT >= OCCURRED_AT)
);

COMMENT ON TABLE  ALERT_EVENT                  IS '预警事件（发生过的记录，没有处置状态）';
COMMENT ON COLUMN ALERT_EVENT.CARD_CODE        IS '可空：手表未登记或未绑定时为空，此时按 DEVICE_IMEI 区分';
COMMENT ON COLUMN ALERT_EVENT.SRC              IS 'THRESHOLD 体征越界 / DEVICE 设备报警（手表 AP10）';
COMMENT ON COLUMN ALERT_EVENT.CODE             IS '事件代码，如 HR_HIGH、SPO2_LOW、SOS、FALL、LOW_BATTERY';
COMMENT ON COLUMN ALERT_EVENT.CATEGORY         IS '大屏六类：SOS FALL HEART_RATE BLOOD_PRESSURE SPO2 TEMPERATURE；其余 OTHER（设备事件）';
COMMENT ON COLUMN ALERT_EVENT.SEVERITY         IS '1 提示 / 2 一般 / 3 严重';
COMMENT ON COLUMN ALERT_EVENT.VAL_TEXT         IS '第一次触发时的值，如 132 或 152/98';
COMMENT ON COLUMN ALERT_EVENT.RULE_GROUP       IS '判断体征越界时用的岗位类别；设备报警为空';
COMMENT ON COLUMN ALERT_EVENT.OCCURRED_AT      IS '第一次发生';
COMMENT ON COLUMN ALERT_EVENT.LAST_OCCURRED_AT IS '最近一次发生（去重期间更新）';
COMMENT ON COLUMN ALERT_EVENT.OCCUR_COUNT      IS '去重期间发生的次数';

CREATE INDEX IX_ALERT_EVENT_TIME     ON ALERT_EVENT (OCCURRED_AT);
CREATE INDEX IX_ALERT_EVENT_CARD     ON ALERT_EVENT (CARD_CODE, OCCURRED_AT);
CREATE INDEX IX_ALERT_EVENT_CATEGORY ON ALERT_EVENT (CATEGORY, OCCURRED_AT);

CREATE TABLE WATCH_LIST (
  ID          NUMBER GENERATED ALWAYS AS IDENTITY,
  CARD_CODE   VARCHAR2(17 CHAR) NOT NULL,
  LIST_TYPE   VARCHAR2(10 CHAR) NOT NULL,
  NOTE        VARCHAR2(200 CHAR),
  EXPIRE_DATE DATE,
  ADDED_BY    VARCHAR2(50 CHAR) NOT NULL,
  ADDED_AT    TIMESTAMP(0) DEFAULT LOCALTIMESTAMP(0) NOT NULL,
  CONSTRAINT PK_WATCH_LIST PRIMARY KEY (ID),
  CONSTRAINT UK_WATCH_LIST UNIQUE (CARD_CODE, LIST_TYPE),
  CONSTRAINT CK_WATCH_LIST_TYPE CHECK (LIST_TYPE IN ('KEY', 'TODAY'))
);

COMMENT ON TABLE  WATCH_LIST             IS '重点监护、今日关注名单（只靠人工加入和移除）';
COMMENT ON COLUMN WATCH_LIST.LIST_TYPE   IS 'KEY 重点监护 / TODAY 今日关注';
COMMENT ON COLUMN WATCH_LIST.EXPIRE_DATE IS 'TODAY 类型当天有效，过了这天自动失效';
