-- V005：岗位类别、预警阈值、预警事件、关注名单。表结构见 docs/04 第六节，预警规则见 docs/03 第四节。
-- 告警是"发生过"的记录，只用来展示和统计，没有处置状态。

CREATE TABLE JOB_GROUP (
  GROUP_CODE       VARCHAR2(20 CHAR) NOT NULL,
  GROUP_NAME       VARCHAR2(50 CHAR) NOT NULL,
  SORT_NO          NUMBER(4) DEFAULT 0 NOT NULL,
  MIN_EVAL_DAYS    NUMBER(3),
  RISK_EVENT_COUNT NUMBER(4),
  CONSTRAINT PK_JOB_GROUP PRIMARY KEY (GROUP_CODE)
);

COMMENT ON TABLE  JOB_GROUP                  IS '岗位类别；每类一套预警阈值。DEFAULT 不能删除';
COMMENT ON COLUMN JOB_GROUP.MIN_EVAL_DAYS    IS '月报：某指标有数据的天数少于它，不参与稳定性评估；空则用 DEFAULT 的';
COMMENT ON COLUMN JOB_GROUP.RISK_EVENT_COUNT IS '月报：一个月里六类告警事件达到它，列为风险职工；空则用 DEFAULT 的';

INSERT INTO JOB_GROUP (GROUP_CODE, GROUP_NAME, SORT_NO, MIN_EVAL_DAYS, RISK_EVENT_COUNT)
VALUES ('DEFAULT', '默认', 0, 5, 3);

-- DEFAULT 不能删除：工种没归类、工种为空时都按它判断
CREATE OR REPLACE TRIGGER TRG_JOB_GROUP_KEEP_DEFAULT
BEFORE DELETE ON JOB_GROUP
FOR EACH ROW
WHEN (OLD.GROUP_CODE = 'DEFAULT')
BEGIN
  RAISE_APPLICATION_ERROR(-20002, '默认岗位类别 DEFAULT 不能删除');
END;
/

CREATE TABLE JOB_KIND_GROUP (
  JOB_KIND   VARCHAR2(50 CHAR) NOT NULL,
  GROUP_CODE VARCHAR2(20 CHAR) NOT NULL,
  UPDATED_BY VARCHAR2(50 CHAR),
  UPDATED_AT TIMESTAMP(0) DEFAULT LOCALTIMESTAMP(0) NOT NULL,
  CONSTRAINT PK_JOB_KIND_GROUP PRIMARY KEY (JOB_KIND),
  CONSTRAINT FK_JOB_KIND_GROUP FOREIGN KEY (GROUP_CODE) REFERENCES JOB_GROUP (GROUP_CODE)
);

COMMENT ON TABLE  JOB_KIND_GROUP          IS '工种归到哪个岗位类别；表里没有的工种都算 DEFAULT';
COMMENT ON COLUMN JOB_KIND_GROUP.JOB_KIND IS '工种，和 POS_PERSON.JOB_KIND 的原值一致';

CREATE TABLE ALERT_RULE (
  GROUP_CODE   VARCHAR2(20 CHAR) NOT NULL,
  METRIC       VARCHAR2(20 CHAR) NOT NULL,
  LOW_LIMIT    NUMBER(6,1),
  HIGH_LIMIT   NUMBER(6,1),
  SEVERITY     NUMBER(1) DEFAULT 2 NOT NULL,
  ENABLED      NUMBER(1) DEFAULT 1 NOT NULL,
  STABLE_PCT   NUMBER(5,2),
  UNSTABLE_PCT NUMBER(5,2),
  UPDATED_AT   TIMESTAMP(0) DEFAULT LOCALTIMESTAMP(0) NOT NULL,
  UPDATED_BY   VARCHAR2(50 CHAR),
  CONSTRAINT PK_ALERT_RULE PRIMARY KEY (GROUP_CODE, METRIC),
  CONSTRAINT FK_ALERT_RULE_GROUP FOREIGN KEY (GROUP_CODE) REFERENCES JOB_GROUP (GROUP_CODE),
  CONSTRAINT CK_ALERT_RULE_METRIC CHECK (METRIC IN ('HEART_RATE', 'SPO2', 'TEMPERATURE', 'BP_SYS', 'BP_DIA')),
  CONSTRAINT CK_ALERT_RULE_SEVERITY CHECK (SEVERITY IN (1, 2, 3)),
  CONSTRAINT CK_ALERT_RULE_ENABLED CHECK (ENABLED IN (0, 1)),
  CONSTRAINT CK_ALERT_RULE_LIMITS CHECK (LOW_LIMIT IS NULL OR HIGH_LIMIT IS NULL OR LOW_LIMIT < HIGH_LIMIT)
);

COMMENT ON TABLE  ALERT_RULE              IS '各岗位类别的预警阈值；某类别缺哪一行就用 DEFAULT 的那一行';
COMMENT ON COLUMN ALERT_RULE.LOW_LIMIT    IS '低于它算偏低；空则不判断偏低';
COMMENT ON COLUMN ALERT_RULE.HIGH_LIMIT   IS '高于它算偏高；空则不判断偏高';
COMMENT ON COLUMN ALERT_RULE.SEVERITY     IS '事件严重程度：1 提示 / 2 一般 / 3 严重';
COMMENT ON COLUMN ALERT_RULE.ENABLED      IS '1 启用 / 0 停用（停用时不产生事件，日汇总也不判异常）';
COMMENT ON COLUMN ALERT_RULE.STABLE_PCT   IS '月报：正常率达到它算稳定；空则用 DEFAULT 的';
COMMENT ON COLUMN ALERT_RULE.UNSTABLE_PCT IS '月报：正常率低于它算不稳定；空则用 DEFAULT 的';

